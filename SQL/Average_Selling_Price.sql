/*
------------------------------------------------------------
Problem : Average Selling Price (LeetCode 1251)

Pattern : SQL / LEFT JOIN / Aggregate Functions /
          Conditional JOIN / GROUP BY /
          NULL Handling / Type Casting

Time Complexity :
JOIN        : O(P * U) naive worst case
Aggregation : O(P * U) naive worst case

Space Complexity : O(P * U) worst case for intermediate
                   join results

Idea:
Calculate the average selling price for every product
based on the number of units sold during each product's
corresponding price validity period.

- Select product_id from the Prices table using alias A.
- Perform a LEFT JOIN between Prices (A) and UnitsSold (B).
- Match records using product_id.
- Apply an additional date condition in the JOIN:
  - B.purchase_date must fall between A.start_date
    and A.end_date.
  - BETWEEN includes both boundary dates.
- Use LEFT JOIN to ensure that products with no
  matching sales records are also included.

Calculating Average Selling Price:
- Multiply A.price by B.units to calculate the total
  revenue generated by each matching sales record.
- Use SUM(A.price * B.units) to calculate the total
  revenue for each product.
- Use SUM(B.units) to calculate the total number
  of units sold for each product.
- Divide total revenue by total units sold to obtain
  the weighted average selling price.
- Cast the numerator to NUMERIC using ::numeric
  to support decimal division and avoid integer
  division.
- Use COALESCE to replace NULL with zero when
  a product has no matching sales records.
- Apply ROUND(..., 2) to round the average selling
  price to two decimal places.

Grouping:
- Use GROUP BY A.product_id to calculate the average
  selling price separately for each product.

Finally:
- Return product_id and its corresponding
  average_price.

Key Insight:
The average selling price must be calculated as
a weighted average rather than a simple arithmetic
average of the individual prices.

Total Revenue / Total Units Sold

The JOIN condition includes both product_id and
the purchase_date validity range.

Placing the date condition inside the ON clause
is important because the LEFT JOIN must preserve
products without matching sales records.

If the date condition were placed in the WHERE
clause, unmatched rows could be eliminated,
effectively changing the LEFT JOIN behavior.

COALESCE handles products without sales by
returning zero instead of NULL.

The NUMERIC cast ensures decimal division in
PostgreSQL, while ROUND ensures two decimal places
in the final result.

P represents the number of rows in the Prices table.
U represents the number of rows in the UnitsSold table.

In a naive execution, joining the two tables can
require O(P * U) comparisons.

Aggregation processes the matching joined records.

The database optimizer may use indexes, hash joins,
or other execution strategies to improve performance.

The query's intermediate join result can contain
multiple matching records per product.

------------------------------------------------------------
*/

SELECT 
    A.product_id,
    ROUND(
        COALESCE(
            SUM(A.price * B.units)::numeric / NULLIF(SUM(B.units), 0),
            0
        ),
        2
    ) AS average_price
FROM Prices A
LEFT JOIN UnitsSold B
    ON A.product_id = B.product_id
    AND B.purchase_date BETWEEN A.start_date AND A.end_date
GROUP BY A.product_id;